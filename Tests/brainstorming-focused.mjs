// Actual rebuilt application, disposable LocalDev database; no provider requests.
import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE);
const base = process.env.BRAINSTORMING_WEB_URL ?? 'http://127.0.0.1:5399';
assert.equal(new URL(base).hostname, '127.0.0.1');
const evidence = resolve(process.env.BRAINSTORMING_EVIDENCE ?? 'artifacts/brainstorming-focused/browser');
const seed = JSON.parse(await readFile(process.env.BRAINSTORMING_WEB_SEED ?? 'artifacts/brainstorming-focused/interactive-seed.json', 'utf8'));
await mkdir(evidence, { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
const errors = [], failedStyles = [], checks = [];
let sends = 0;
page.on('pageerror', e => errors.push(e.message));
page.on('response', r => { if (r.url().includes('.css') && r.status() >= 400) failedStyles.push(r.url()); });
page.on('request', r => { if (r.url().includes('/conversation/stream')) sends++; });
const source = async () => { const r = await page.request.get(`${base}/api/brainstorming/sources/${seed.documentId}`); assert(r.ok()); return r.json(); };
const unchanged = async () => { const s = await source(); for (const p of seed.sourcePages) assert.equal(s.pages.find(x => x.id === p.Id)?.content, p.Content); assert.equal(s.pages.length, seed.sourcePages.length); };
const button = name => page.getByRole('button', { name, exact: true });
const rail = page.getByRole('navigation', { name: 'Brainstorm panes' });
const proposal = page.getByRole('region', { name: 'Proposed prose review', exact: true });
const box = page.getByRole('textbox', { name: 'Proposed prose editor', exact: true });
const composer = page.getByRole('textbox', { name: 'Your message', exact: true });
const bounds = async locator => locator.evaluate(el => { const b = el.getBoundingClientRect(); return { top: b.top, bottom: b.bottom, right: b.right, viewport: innerHeight, fits: b.bottom <= innerHeight + 1 && b.right <= innerWidth + 1 && b.top >= 0 }; });
try {
    for (let attempt = 0; attempt < 40; attempt++) {
        try { if ((await page.request.get(`${base}/api/auth/me`)).ok()) break; } catch { /* Owned host starting. */ }
        if (attempt === 39) throw new Error('Acceptance host did not become ready.');
        await new Promise(done => setTimeout(done, 500));
    }
    await page.goto(`${base}/app/documents/${seed.documentId}/sections/${seed.sectionId}`);
    await button('Brainstorm').click({ timeout: 45000 });
    // Initial host preparation completes asynchronously and returns to Chat.
    await page.getByText('Context ready', {exact:true}).waitFor();
    await button('History').click();
    await button('Find synced conversations').click();
    await page.getByRole('combobox', { name: /^Saved conversation/ }).selectOption(seed.restoredSessionId);
    await button('Open saved conversation').click();
    await box.waitFor();
    assert.equal(await page.locator('.editor-main').isVisible(), false);
    assert.equal(await page.locator('.brainstorm-outline').isVisible(), false);
    assert.equal(await page.locator('.device-editor-toolbar').filter({ visible: true }).count(), 0);
    assert.equal(await page.getByRole('button', { name: 'Previous version', exact: true }).isVisible(), false);
    assert.equal(await proposal.getByText('Proposal provenance', { exact: true }).isVisible(), false);
    assert((await bounds(button('Review & keep'))).fits);
    assert((await bounds(composer)).fits);
    checks.push('Draft is the sole visible editor; outline and detailed review controls start collapsed; review and composer remain in view.');
    const prose = 'The Arctic wind bit at Anna’s face as she crouched beside the gleaming ice sheet, her breath crystallising in the frigid air. Around her, the team checked their equipment and marked the drill site.\n\nThe motorised drill thrummed to life, its steady vibration echoing across the ice. Each layer held clues — trapped bubbles, ancient dust, a record of the Earth’s changing climate.\n\nAs she helped label the core and prepared it for transport to the lab, Anna felt a surge of purpose. In this harsh, beautiful place, their careful work added another piece to the story of a planet in flux.';
    await box.fill(prose);
    await box.focus(); await page.keyboard.press('Control+A');
    if (await proposal.getByRole('button', { name:'Bold', exact:true }).getAttribute('aria-pressed') === 'true') await proposal.getByRole('button', { name:'Bold', exact:true }).click();
    await composer.fill('Add more sensory detail, keeping the science accurate.');
    await proposal.getByRole('button', { name: 'Compare', exact: true }).click();
    await page.getByRole('heading', { name: 'Captured manuscript versus proposal', exact: true }).waitFor();
    assert((await page.locator('.brainstorm-comparison').innerText()).includes('The Arctic wind'));
    await proposal.getByRole('button', { name: 'Details', exact: true }).click();
    assert(await button('Previous version').isVisible());
    await proposal.getByRole('button', { name: 'Draft', exact: true }).click();
    assert((await box.innerText()).includes('The Arctic wind'));
    assert.equal(await composer.inputValue(), 'Add more sensory detail, keeping the science accurate.');
    await button('Save version').click();
    await page.waitForFunction(() => document.querySelector('.working-history > summary')?.textContent.includes('2'));
    await unchanged();
    checks.push('Draft/Compare/Details preserve exact edits and composer; Save version checkpoints without changing manuscript.');
    await page.screenshot({ path: resolve(evidence, 'focused-wide.png') });
    await button('+ Alternative').click();
    await page.getByLabel('Alternative name', {exact:true}).fill('Quieter arrival');
    await button('Create alternative').click();
    await button('Quieter arrival').waitFor();
    await box.fill('Anna waited beside the silent drill.');
    await button('Save version').click();
    await page.waitForFunction(() => document.querySelector('.proposal-save-state')?.textContent.includes('All 2 versions saved'));
    await button('Main draft').click();
    await page.waitForFunction(() => document.querySelector('[aria-label="Proposed prose editor"]')?.textContent.includes('The Arctic wind'));
    await page.locator('.working-history > summary').click();
    await page.locator('.working-history-row').first().getByRole('button',{name:'Preview / compare'}).click();
    await page.getByRole('region',{name:'Saved version preview'}).waitFor();
    await page.screenshot({path:resolve(evidence,'working-draft-history.png')});
    await button('Restore as a new version').click();
    await page.waitForFunction(() => document.querySelector('.working-history > summary')?.textContent.includes('3'));
    await page.locator('.working-history > summary').click();
    assert((await box.innerText()).includes('The Arctic wind'));await unchanged();
    checks.push('Named alternative retains its own edited draft; Main draft retains earlier text; version preview and restore add a snapshot without deleting later history.');
    await rail.getByRole('button',{name:'Outline',exact:true}).click();
    await page.screenshot({path:resolve(evidence,'continuous-working-draft.png')});
    await rail.getByRole('button',{name:'Outline',exact:true}).click();
    // Real shared formatting commands and state, including keyboard and disabled generation controls, have a separate two-factory browser test.
    await box.focus(); await page.keyboard.press('Control+Home');
    await page.getByRole('combobox', { name: 'Draft paragraph style', exact: true }).selectOption('heading:2');
    assert(await box.locator('h2').count() > 0);
    await page.getByRole('combobox', { name: 'Draft paragraph style', exact: true }).selectOption('paragraph');
    await rail.getByRole('button', { name: 'Manuscript', exact: true }).click();
    assert(await page.locator('.editor-main').isVisible());
    assert.equal(await box.isVisible(), false);
    await rail.getByRole('button', { name: 'Brainstorm', exact: true }).click();
    assert((await box.innerText()).includes('The Arctic wind'));
    checks.push('Manuscript/draft navigation retains the mounted editor; compact paragraph dropdown changes real rich-text formatting.');
    for (const [width, height] of [[900,800], [390,844]]) {
        await page.setViewportSize({ width, height });
        await rail.getByRole('button', { name: 'Brainstorm', exact: true }).click();
        assert(await box.isVisible());
        assert((await bounds(button('Review & keep'))).fits, JSON.stringify(await bounds(button('Review & keep'))));
        assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
        await page.screenshot({ path: resolve(evidence, `draft-${width}.png`) });
        await rail.getByRole('button', { name: 'Conversation', exact: true }).click();
        assert((await bounds(composer)).fits);
        assert.equal(await composer.inputValue(), 'Add more sensory detail, keeping the science accurate.');
        await page.screenshot({ path: resolve(evidence, `conversation-${width}.png`) });
    }
    checks.push('900px and 390px panes retain draft/composer and keep primary actions on screen without horizontal overflow.');
    await page.setViewportSize({ width:1600, height:1000 });
    await rail.getByRole('button', { name:'Brainstorm', exact:true }).click();
    await box.fill((prose + '\n\n').repeat(18));
    await page.locator('.proposal-content').first().evaluate(el => { el.scrollTop = el.scrollHeight; });
    assert((await bounds(button('Review & keep'))).fits);
    assert((await bounds(composer)).fits);
    await page.screenshot({ path: resolve(evidence, 'long-draft.png') });
    await box.fill(prose);
    await proposal.getByRole('button', { name:'Details', exact:true }).click();
    await page.getByLabel('New section title', { exact:true }).fill('Reviewed Arctic opening');
    await proposal.getByRole('button', { name:'Draft', exact:true }).click();
    await button('Review & keep').click();
    await page.getByRole('region', { name:'Confirm manuscript application', exact:true }).waitFor();
    await unchanged();
    assert((await bounds(button('Add here'))).fits);
    await page.screenshot({ path:resolve(evidence, 'review-insertion.png') });
    await button('Cancel review').click();
    assert((await box.innerText()).includes('The Arctic wind'));
    await unchanged();
    checks.push('Long prose scrolls independently; insertion displays the exact confirmation without manuscript mutation; cancellation retains draft.');
    assert.equal(sends, 0); assert.deepEqual(errors, []); assert.deepEqual(failedStyles, []);
    await writeFile(resolve(evidence, 'result.json'), JSON.stringify({ checks, sends, errors, failedStyles, browser:browser.version(), scope:'Actual rebuilt web application and disposable LocalDev data; synthetic restored draft, no live AI or native interaction.' }, null, 2));
    console.log(JSON.stringify({ checks, sends }, null, 2));
} catch (error) {
    await page.screenshot({ path:resolve(evidence, 'failure.png'), fullPage:true });
    await writeFile(resolve(evidence, 'failure.txt'), await page.locator('body').innerText());
    throw error;
} finally { await browser.close(); }
