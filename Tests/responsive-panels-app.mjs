// Actual rebuilt Blazor client; the caller supplies a disposable LocalDev fixture.
import assert from 'node:assert/strict';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {resolve} from 'node:path';
import {createRequire} from 'node:module';
const {chromium}=createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base=process.env.PROSA_PANELS_URL || 'http://127.0.0.1:5403';
assert.equal(new URL(base).hostname,'127.0.0.1');
const seed=JSON.parse(await readFile(process.env.PROSA_PANELS_SEED || 'artifacts/brainstorming-focused/interactive-seed.json','utf8'));
const evidence=resolve('artifacts/responsive-panels/application');await mkdir(evidence,{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:390,height:844}}),errors=[],checks=[];
page.on('pageerror',e=>errors.push(e.message));
const root=page.locator('[data-responsive-panels]');
const button=side=>page.locator(`[data-panel-action="${side}"]`);
const state=()=>root.evaluate(e=>({...e.dataset}));
try {
    await page.goto(`${base}/app/documents/${seed.documentId}/sections/${seed.sectionId}`);
    await root.waitFor({timeout:45000});
    await page.waitForFunction(()=>document.querySelector('[data-responsive-panels]')?.dataset.panelsReady==='true');
    const original=await page.locator('.ProseMirror').first().innerHTML();
    assert.equal((await state()).openDrawer,'');
    await page.screenshot({path:resolve(evidence,'phone-writing.png')});
    await button('right').click();
    await page.getByRole('dialog',{name:'Writing tools'}).waitFor();
    await page.getByRole('tab',{name:'Notes & Tasks',exact:true}).click();
    await page.screenshot({path:resolve(evidence,'phone-tools.png')});
    await button('close-right').click();
    await button('left').click();
    await page.getByRole('dialog',{name:'Projects and outline'}).waitFor();
    await page.screenshot({path:resolve(evidence,'phone-outline.png')});
    await page.keyboard.press('Escape');
    assert.equal(await button('left').evaluate(e=>e===document.activeElement),true);
    await button('focus').click();
    await page.waitForFunction(()=>document.querySelector('[data-responsive-panels]').classList.contains('is-focus-mode'));
    await button('right').click();
    await page.getByRole('dialog',{name:'Writing tools'}).waitFor();
    assert.equal(await root.evaluate(e=>e.classList.contains('is-focus-mode')),false);
    await button('close-right').click();
    assert.equal(await page.locator('.ProseMirror').first().innerHTML(),original);
    checks.push('Real mobile client opens both drawers and Notes; Escape restores focus; opening tools exits focus without changing manuscript');
    await page.setViewportSize({width:1600,height:1000});
    await page.waitForFunction(()=>document.querySelector('[data-responsive-panels]').dataset.panelsCompact==='false');
    assert.equal((await state()).leftOpen,'true');
    await button('right').click();assert.equal((await state()).rightOpen,'false');
    await button('left').click();
    await page.reload();
    await page.waitForFunction(()=>document.querySelector('[data-responsive-panels]')?.dataset.panelsReady==='true');
    assert.equal((await state()).rightOpen,'false');assert.equal((await state()).leftOpen,'false');
    await button('left').click();await button('right').click();
    await page.getByRole('tab',{name:'Navigator',exact:true}).click();
    assert.equal(await page.locator('#editor-outline-add-node-type').count(),1);
    assert.equal(await page.locator('#add-node-type').count(),1);
    await page.screenshot({path:resolve(evidence,'desktop-panels.png')});
    checks.push('Real desktop client docks both panels and remembers visibility after reload');
    await page.getByRole('button',{name:'Brainstorm',exact:true}).click();
    const rail=page.getByRole('navigation',{name:'Brainstorm panes'});await rail.waitFor();
    await rail.getByRole('button',{name:'Manuscript',exact:true}).click();
    assert.equal(await button('left').isVisible(),false);assert.equal(await button('right').isVisible(),false);
    await page.getByRole('button',{name:'Leave Brainstorm',exact:true}).click();
    await button('left').waitFor();await button('right').waitFor();
    checks.push('Brainstorm retains its dedicated panes; editor panel controls return after leaving');
    await page.setViewportSize({width:390,height:844});
    await page.waitForFunction(()=>document.querySelector('[data-responsive-panels]').dataset.panelsCompact==='true');
    await button('left').click();
    await page.locator('.editor-navigation-scroll nav[aria-label="Manuscript sections"] button').first().click();
    await page.waitForFunction(()=>document.querySelector('[data-responsive-panels]')?.dataset.openDrawer==='');
    checks.push('Selecting a manuscript section in the real client closes the compact navigation drawer');
    assert.deepEqual(errors,[]);
    await writeFile(resolve(evidence,'results.json'),JSON.stringify({base,checks,errors},null,2));console.log(JSON.stringify({checks,errors},null,2));
} finally {await browser.close();}
